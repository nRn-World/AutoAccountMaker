let currentLanguage = DEFAULT_LANGUAGE;

function normalizeLanguage(lang) {
  return SUPPORTED_LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
}

/** Slå upp "a.b.c" i den aktuella ordlistan, med engelska som fallback. */
function lookup(dict, key) {
  return key.split('.').reduce((acc, part) => (acc == null ? undefined : acc[part]), dict);
}

function t(key, ...args) {
  const value = lookup(DICT[currentLanguage], key) ?? lookup(DICT[DEFAULT_LANGUAGE], key);
  if (typeof value === 'function') return value(...args);
  if (value == null) return key;
  return value;
}

/** Sätter <html lang> och dir (RTL för arabiska). */
function applyDocumentLanguage(lang, root) {
  const normalized = normalizeLanguage(lang);
  currentLanguage = normalized;

  const doc = root || (typeof document !== 'undefined' ? document : null);
  const el = doc && doc.documentElement;
  if (el && el.setAttribute) {
    el.setAttribute('lang', normalized);
    el.setAttribute('dir', RTL_LANGUAGES.includes(normalized) ? 'rtl' : 'ltr');
  }
  return normalized;
}

/**
 * Översätter alla element med data-i18n i ett underträd.
 *   data-i18n            -> textContent
 *   data-i18n-placeholder-> placeholder
 *   data-i18n-title      -> title
 *   data-i18n-aria-label -> aria-label
 *   data-i18n-value      -> value
 */
function applyTranslations(root, lang) {
  const scope = root || document;
  if (lang) currentLanguage = normalizeLanguage(lang);
  applyDocumentLanguage(currentLanguage, scope);

  const ATTRS = [
    ['data-i18n', 'textContent'],
    ['data-i18n-placeholder', 'placeholder'],
    ['data-i18n-title', 'title'],
    ['data-i18n-aria-label', 'aria-label'],
    ['data-i18n-value', 'value'],
  ];

  for (const [attr, prop] of ATTRS) {
    scope.querySelectorAll(`[${attr}]`).forEach((el) => {
      const key = el.getAttribute(attr);
      if (!key) return;
      el[prop] = t(key);
    });
  }
}

/** Laddar språket från inställningarna och översätter sidan. */
async function initI18n() {
  try {
    const res = await chrome.runtime.sendMessage({ action: 'getSettings' });
    currentLanguage = normalizeLanguage(res?.settings?.language);
  } catch {
    currentLanguage = DEFAULT_LANGUAGE;
  }
  applyTranslations(document, currentLanguage);
  return currentLanguage;
}

/**
 * Översätter ett svar från background.js. Background returnerar errorCode
 * (en stabil nyckel); message används bara som sista utväg.
 * Placeholders som {status} och {code} fylls i från fält på svaret.
 */
function translateError(result, fallbackKey) {
  if (!result) return fallbackKey ? t(fallbackKey) : '';
  const code = result.errorCode;
  let key = code ? 'err.' + code : '';
  if (key !== 'err.undefined' && code && t(key) !== key) {
    let msg = t(key);
    if (result.status) msg = msg.replace(/\{status\}/g, String(result.status));
    if (result.code) msg = msg.replace(/\{code\}/g, String(result.code));
    return msg;
  }
  if (result.error) return result.error;
  return fallbackKey ? t(fallbackKey) : '';
}

if (typeof window !== 'undefined') {
  window.I18N = {
    SUPPORTED_LANGUAGES,
    DEFAULT_LANGUAGE,
    RTL_LANGUAGES,
    LANGUAGE_NAMES,
    DICT,
    t,
    translateError,
    applyTranslations,
    applyDocumentLanguage,
    initI18n,
    get language() {
      return currentLanguage;
    },
    set language(lang) {
      currentLanguage = normalizeLanguage(lang);
      applyTranslations(document, currentLanguage);
    },
  };
}
